"""Re-runnable: embeds the crew avatars (Hunter, Sean) into sketchy-golf.html between CREW_ART markers.
In-game art = the hat version where the golfer has one; home-screen art = always the no-hat version."""
import re, json
p='/home/claude/golf/sketchy-golf.html'; s=open(p).read()
C='/home/claude/golf/avatar/crew/'
GAME = {'hunter': 'hunter/avatar-hat.svg', 'sean': 'sean/avatar.svg'}   # what they wear on the course
HOME = {'hunter': 'hunter/avatar.svg', 'sean': 'sean/avatar.svg'}       # home screen: no hats
def split(svg):  # -> background svg + head-layer svg (defs travel with the head), same as Neil's
    svg=svg.strip(); d0=svg.index('<defs>'); d1=svg.index('</defs>')+7; defs=svg[d0:d1]; h=svg.index('<g id="avHead">')
    return svg[:d0]+svg[d1:h]+'</svg>'+'<svg class="avHeadL" viewBox="0 0 100 100" aria-hidden="true">'+defs+svg[h:]
def tables(js):
    m=re.search(r'^\s*let MOUTH = (\{.*?\n\s*\});', js, re.S | re.M); b=re.search(r'^\s*let BROWS = (\{.*?\n\s*\});', js, re.S | re.M)
    return m.group(1), b.group(1)
lines=[]
for who in ['hunter','sean']:
    g=split(open(C+GAME[who]).read()); h=split(open(C+HOME[who]).read()); M,B=tables(open(C+who+'/av-presets.js').read())
    lines.append(f"AV.addArt('{who}', {json.dumps(g)}, {M}, {B}, {json.dumps(h)});")
block='/* CREW_ART_BEGIN — generated by crew_integrate.py */\n'+'\n'.join(lines)+'\n/* CREW_ART_END */\n'
if '/* CREW_ART_BEGIN' in s:
    i=s.index('/* CREW_ART_BEGIN'); j=s.index('/* CREW_ART_END */\n')+len('/* CREW_ART_END */\n'); s=s[:i]+block+s[j:]
